/// The `codec` subcommand: the whole corpus, one JSON record per case.
pub fn codec_command(out: &mut dyn Write) -> Result<(), Box<dyn Error>> {
    // The generator itself, published first. A Zig test that cannot
    // reproduce these states cannot claim the corpus it replays came from
    // this generator, so the states are part of the corpus.
    let mut rng = Lcg::new(BASE_SEED);
    let states: Vec<Json> = (0..LCG_STATES)
        .map(|_| Json::String(format!("{:016x}", rng.next())))
        .collect();
    emit(
        out,
        &json!({
            "kind": "codec-lcg",
            "mul": format!("{:016x}", LCG_MUL),
            "add": format!("{:016x}", LCG_ADD),
            "seed": format!("{:016x}", BASE_SEED),
            "states": states,
        }),
    )?;

    // The RLE codecs, and with them the slab metadata and the loader's cut:
    // a slab *is* an RLE or a boolean encoding, so the same records answer
    // for the slab family too.
    for ty in RLE_TYPES {
        for case in rle_cases(ty) {
            let bytes = rle_bytes(ty, &case.values);
            let answer = rle_slab(ty, &bytes)?;
            emit(
                out,
                &json!({
                    "kind": "codec",
                    "codec": ty.name(),
                    "family": "rle",
                    "case": case.name,
                    "seed": format!("{:016x}", case.seed),
                    "runs": runs_json(&case.values),
                    "len": case.values.len(),
                    "hex": hex_encode(&bytes),
                    "slab_len": answer.len,
                    "segments": answer.segments,
                    "tail_bytes": answer.tail_bytes,
                    "tail_lit_tail": answer.tail_lit_tail,
                    "split": { "loader_max_segments": LOADER_MAX_SEGMENTS, "lens": answer.split },
                }),
            )?;
        }
    }

    // The boolean family through the same `Ty` the other three go through, so
    // the record's `codec` name has one source.
    let ty = Ty::Bool;
    for case in bool_cases() {
        let bytes = bool_bytes(&case.values);
        let answer = bool_slab(&bytes)?;
        emit(
            out,
            &json!({
                "kind": "codec",
                "codec": ty.name(),
                "family": "bool",
                "case": case.name,
                "seed": format!("{:016x}", case.seed),
                "runs": runs_json(&case.values),
                "len": case.values.len(),
                "hex": hex_encode(&bytes),
                "slab_len": answer.len,
                "segments": answer.segments,
                "tail_bytes": answer.tail_bytes,
                "tail_lit_tail": Json::Null,
                "split": { "loader_max_segments": LOADER_MAX_SEGMENTS, "lens": answer.split },
            }),
        )?;
    }

    for ty in DELTA_TYPES {
        for case in delta_cases(ty) {
            let bytes = delta_bytes(ty, &case.values);
            // A delta slab is an RLE column of `Option<i64>` deltas
            // (`delta/mod.rs:19-26`), so the nullable 64-bit family is the
            // one that reads it.
            let answer = rle_slab(Ty::OptI64, &bytes)?;
            emit(
                out,
                &json!({
                    "kind": "codec",
                    "codec": format!("delta-{}", ty.bare()),
                    "family": "delta",
                    "case": case.name,
                    "seed": format!("{:016x}", case.seed),
                    "runs": runs_json(&case.values),
                    "len": case.values.len(),
                    "hex": hex_encode(&bytes),
                    "slab_len": answer.len,
                    "segments": answer.segments,
                    "tail_bytes": answer.tail_bytes,
                    "tail_lit_tail": answer.tail_lit_tail,
                    "split": { "loader_max_segments": LOADER_MAX_SEGMENTS, "lens": answer.split },
                }),
            )?;
        }
    }

    for ty in PREFIX_TYPES {
        for case in prefix_cases(ty) {
            // A prefix column's rows are lengths in an ordinary RLE column
            // (`prefix.rs:414-415`), so the wire bytes are the RLE ones for
            // the same type.
            let bytes = rle_bytes(ty, &case.values);
            let answer = rle_slab(ty, &bytes)?;
            let targets = prefix_index_targets(ty, &case.values);
            let indexes = prefix_indexes(ty, &case.values, &targets);
            emit(
                out,
                &json!({
                    "kind": "codec",
                    "codec": format!("prefix-{}", ty.bare()),
                    "family": "prefix",
                    "case": case.name,
                    "seed": format!("{:016x}", case.seed),
                    "runs": runs_json(&case.values),
                    "len": case.values.len(),
                    "hex": hex_encode(&bytes),
                    "slab_len": answer.len,
                    "segments": answer.segments,
                    "tail_bytes": answer.tail_bytes,
                    "tail_lit_tail": answer.tail_lit_tail,
                    "split": { "loader_max_segments": LOADER_MAX_SEGMENTS, "lens": answer.split },
                    "prefixes": prefix_sums(ty, &case.values),
                    "index_targets": targets.iter().map(|t| Json::String(t.to_string())).collect::<Vec<Json>>(),
                    "indexes": indexes,
                }),
            )?;
        }
    }

    for case in btree_cases() {
        let mut queries: Vec<Json> = Vec::new();
        for (lo, hi) in &case.queries {
            let answer = btree_answer(&case.values, *lo, *hi);
            queries.push(json!({
                "lo": lo.to_string(),
                "hi": hi.to_string(),
                "items": answer,
            }));
        }
        let values: Vec<V> = case.values.iter().map(|v| V::S(*v as i128)).collect();
        emit(
            out,
            &json!({
                "kind": "codec-btree",
                "codec": "btree-i64",
                "family": "btree",
                "case": case.name,
                "seed": format!("{:016x}", case.seed),
                "runs": runs_json(&values),
                "len": case.values.len(),
                "queries": queries,
            }),
        )?;
    }

    Ok(())
}

/// A case's values as maximal runs, `[[count, value], …]`, with a value
/// that is a decimal **string** and a null that is `null`.
///
/// **Strings, not numbers.** The corpus holds values up to `u64::MAX`, and
/// a JSON number that wide is not exactly representable everywhere it is
/// read; a decimal string is. Run-length form, because a 16 385-value
/// repeat run is 16 385 numbers in a file and about twenty bytes here, and
/// the form is lossless either way.
fn runs_json(values: &[V]) -> Json {
    let mut out: Vec<Json> = Vec::new();
    let mut i = 0;
    while i < values.len() {
        let v = values[i];
        let mut n = 1;
        while i + n < values.len() && values[i + n] == v {
            n += 1;
        }
        out.push(json!([n, v.json()]));
        i += n;
    }
    Json::Array(out)
}
