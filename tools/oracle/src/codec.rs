// ── The corpus ───────────────────────────────────────────────────────────────

/// One case: a name, the seed that generated it, and its values.
struct Case {
    name: String,
    seed: u64,
    values: Vec<V>,
}

/// The seed of case `index`, mixed from [`BASE_SEED`] so every case is
/// independent and one is replayable on its own.
fn case_seed(index: u64) -> u64 {
    BASE_SEED ^ index.wrapping_mul(0x9E37_79B9_7F4A_7C15)
}

/// A draw in `lo..=hi`, for the random streams.
fn draw(rng: &mut Lcg, lo: i128, hi: i128) -> i128 {
    if hi <= lo {
        return lo;
    }
    let span = (hi - lo) as u64;
    lo + rng.below(span + 1) as i128
}

/// `count` copies of `v`, as a `Vec`.
fn repeat(v: V, count: usize) -> Vec<V> {
    vec![v; count]
}

/// The random streams, twenty-four per type, in four shapes.
///
/// The shapes are the point: a small alphabet makes runs form *and* merge,
/// the full domain makes a value's width change inside one slab, blocks of
/// equal values put a repeat run next to a literal one, and a walk makes
/// consecutive values close together. A generator that only did the first
/// would pass a codec with a broken literal run.
fn random_cases_in(ty: Ty, lo: i128, hi: i128) -> Vec<Case> {
    const STREAMS: u64 = 24;
    let (dom_lo, dom_hi) = ty.domain();
    let lo = lo.max(dom_lo);
    let hi = hi.min(dom_hi);
    let alpha: Vec<i128> = [0i128, 1, 2, 3]
        .into_iter()
        .filter(|v| *v >= lo && *v <= hi)
        .collect();
    let mut out = Vec::new();
    for k in 0..STREAMS {
        let seed = case_seed(k + 1);
        let mut rng = Lcg::new(seed);
        let mut values: Vec<V> = Vec::new();
        match k % 4 {
            // A small alphabet: long runs, and runs that merge across the
            // block boundaries.
            0 => {
                let n = rng.below(96);
                for _ in 0..n {
                    let v = if alpha.is_empty() {
                        draw(&mut rng, lo, hi)
                    } else {
                        alpha[rng.below(alpha.len() as u64) as usize]
                    };
                    values.push(V::S(v));
                }
            }
            // The full domain: every value's width is its own.
            1 => {
                let n = rng.below(64);
                for _ in 0..n {
                    values.push(V::S(draw(&mut rng, lo, hi)));
                }
            }
            // Blocks of equal values, so a repeat run meets a literal run.
            2 => {
                let blocks = rng.below(24);
                for _ in 0..blocks {
                    let n = (1 + rng.below(6)) as usize;
                    let v = if alpha.is_empty() {
                        V::S(draw(&mut rng, lo, hi))
                    } else {
                        V::S(alpha[rng.below(alpha.len() as u64) as usize])
                    };
                    values.extend(repeat(v, n));
                }
            }
            // A walk: consecutive values are close, so a delta column's
            // deltas are small and a prefix column's sums are dense.
            _ => {
                let n = rng.below(80);
                let mut at = draw(&mut rng, lo, hi);
                for _ in 0..n {
                    values.push(V::S(at));
                    at = (at + (rng.below(9) as i128) - 4).clamp(lo, hi);
                }
            }
        }
        // A nullable column gets its nulls from the same stream, so a null
        // run lands *inside* whatever the shape produced rather than beside
        // it, and every case ends on a null.
        if ty.nullable() {
            let mut with_nulls: Vec<V> = Vec::with_capacity(values.len() * 2);
            let mut null_rng = Lcg::new(seed ^ 0x9E37_79B9_7F4A_7C15);
            for v in values {
                with_nulls.push(v);
                if null_rng.below(6) == 0 {
                    with_nulls.push(V::N);
                }
            }
            with_nulls.push(V::N);
            values = with_nulls;
        }
        out.push(Case {
            name: format!("random_{k}"),
            seed,
            values,
        });
    }
    out
}

/// The random streams over the type's own domain, clipped to 2^35 either way
/// so a wide type still gets a stream whose values are all in one column.
fn random_cases(ty: Ty) -> Vec<Case> {
    random_cases_in(ty, -(1i128 << 35), 1i128 << 35)
}

/// The boolean corpus, in the same two halves: the run-width boundaries and
/// the seeded streams.
fn bool_cases() -> Vec<Case> {
    let mut out = vec![Case {
        name: "empty".into(),
        seed: 0,
        values: vec![],
    }];
    for &n in RUN_COUNTS {
        for start in [false, true] {
            out.push(Case {
                name: format!("run_{n}_{}", if start { "true" } else { "false" }),
                seed: 0,
                values: repeat(V::S(i128::from(start)), n),
            });
        }
    }
    out.push(Case {
        name: "one_false".into(),
        seed: 0,
        values: vec![V::S(0)],
    });
    out.push(Case {
        name: "one_true".into(),
        seed: 0,
        values: vec![V::S(1)],
    });
    out.push(Case {
        name: "alternating_odd".into(),
        seed: 0,
        values: (0..101).map(|i| V::S(i % 2)).collect(),
    });
    out.push(Case {
        name: "alternating_even".into(),
        seed: 0,
        values: (0..100).map(|i| V::S(i % 2)).collect(),
    });
    // A run on each side of a single opposite value: three runs, and the
    // opening one is the zero-count pad when the slab starts on `true`.
    for n in [1usize, 2, 63, 64, 127, 128, 16383, 16384] {
        out.push(Case {
            name: format!("sandwich_false_{n}"),
            seed: 0,
            values: [repeat(V::S(0), n), vec![V::S(1)], repeat(V::S(0), n)].concat(),
        });
        out.push(Case {
            name: format!("sandwich_true_{n}"),
            seed: 0,
            values: [repeat(V::S(1), n), vec![V::S(0)], repeat(V::S(1), n)].concat(),
        });
    }
    // The seeded streams, in three shapes: a small alphabet, a long
    // alternation, and blocks of equal values.
    for k in 0..24u64 {
        let seed = case_seed(1000 + k);
        let mut rng = Lcg::new(seed);
        let mut values: Vec<V> = Vec::new();
        match k % 3 {
            0 => {
                let n = rng.below(128);
                for _ in 0..n {
                    values.push(V::S(rng.below(2) as i128));
                }
            }
            1 => {
                let n = rng.below(200);
                for i in 0..n {
                    values.push(V::S((i % 2) as i128));
                }
            }
            _ => {
                let blocks = rng.below(40);
                for _ in 0..blocks {
                    let n = (1 + rng.below(9)) as usize;
                    values.extend(repeat(V::S(rng.below(2) as i128), n));
                }
            }
        }
        out.push(Case {
            name: format!("random_{k}"),
            seed,
            values,
        });
    }
    out
}

/// The RLE corpus for one type: the empty slab, the smallest non-empty
/// ones, the run-width boundaries, the value-width boundaries in pairs and
/// as one long literal run, the shapes, the null placements, and the seeded
/// streams.
fn rle_cases(ty: Ty) -> Vec<Case> {
    let bounds: Vec<i128> = RLE_BOUNDARY
        .iter()
        .copied()
        .filter(|v| ty.in_domain(*v))
        .collect();
    let first = bounds.first().copied().unwrap_or(0);
    let second = bounds.get(1).copied().unwrap_or(first);
    let third = bounds.get(2).copied().unwrap_or(first);
    let mut out: Vec<Case> = Vec::new();

    macro_rules! push {
        ($name:expr, $values:expr) => {
            out.push(Case {
                name: $name.to_string(),
                seed: 0,
                values: $values,
            })
        };
    }

    // The empty slab, and the two smallest non-empty ones.
    push!("empty", vec![]);
    push!("one", vec![V::S(first)]);
    push!("two_equal", vec![V::S(first), V::S(first)]);
    push!("two_differ", vec![V::S(first), V::S(second)]);
    push!("three_aba", vec![V::S(first), V::S(second), V::S(first)]);
    push!("three_all_differ", vec![V::S(first), V::S(second), V::S(third)]);

    // Every run count whose header width changes.
    for &count in RUN_COUNTS {
        push!(format!("repeat_{count}"), repeat(V::S(first), count));
        if ty.nullable() {
            push!(format!("null_{count}"), repeat(V::N, count));
        }
    }

    // Every adjacent pair of boundary values, so a header width and a
    // payload width that disagree have somewhere to disagree.
    for i in 0..bounds.len().saturating_sub(1) {
        push!(
            format!("pair_{i}"),
            vec![V::S(bounds[i]), V::S(bounds[i + 1])]
        );
    }

    // The whole boundary list as one literal run: every width in one slab.
    push!(
        "boundary_literal",
        bounds.iter().copied().map(V::S).collect::<Vec<V>>()
    );

    // Shapes that are not a run list: a long run, an ascending walk, a
    // descending walk, and an alternation.
    push!("all_equal_300", repeat(V::S(first), 300));
    push!(
        "ascending",
        (0..96).map(|i| V::S(i as i128)).collect::<Vec<V>>()
    );
    push!(
        "descending",
        (0..96).rev().map(|i| V::S(i as i128)).collect::<Vec<V>>()
    );
    let mut alt: Vec<V> = Vec::new();
    for i in 0..96 {
        alt.push(V::S(if i % 2 == 0 { first } else { second }));
    }
    push!("alternating", alt);

    // A null at each end and in the middle, next to values that repeat
    // across it, so the null run has to be a run of its own.
    if ty.nullable() {
        push!("null_alone", vec![V::N]);
        push!("null_then_value", vec![V::N, V::S(first)]);
        push!("value_then_null", vec![V::S(first), V::N]);
        push!(
            "nulls_both_ends",
            vec![V::N, V::S(first), V::S(second), V::N]
        );
        push!(
            "null_sandwiched",
            [repeat(V::S(first), 70), vec![V::N], repeat(V::S(first), 70)].concat()
        );
        push!(
            "nulls_and_boundaries",
            bounds
                .iter()
                .copied()
                .map(V::S)
                .chain(repeat(V::N, 3))
                .collect::<Vec<V>>()
        );
    }

    out.extend(random_cases(ty));
    out
}

/// The delta corpus for one type.
///
/// The boundary list is the delta one, so no pair asks for a difference the
/// wire cannot carry; everything else is shared with the RLE corpus, which
/// is the point: the same shapes through a different transform.
fn delta_cases(ty: Ty) -> Vec<Case> {
    let Some((lo, hi)) = ty.delta_domain() else {
        return Vec::new();
    };
    let list = if lo == 0 {
        DELTA_BOUNDARY_UNSIGNED
    } else {
        DELTA_BOUNDARY_SIGNED
    };
    let bounds: Vec<i128> = list
        .iter()
        .copied()
        .filter(|v| *v >= lo && *v <= hi)
        .collect();
    let first = bounds.first().copied().unwrap_or(0);
    let mut out: Vec<Case> = Vec::new();

    macro_rules! push {
        ($name:expr, $values:expr) => {
            out.push(Case {
                name: $name.to_string(),
                seed: 0,
                values: $values,
            })
        };
    }

    push!("empty", vec![]);
    push!("one", vec![V::S(first)]);
    push!("zero_deltas", repeat(V::S(0), 8));
    push!("all_zero_100", repeat(V::S(0), 100));
    push!("all_equal_300", repeat(V::S(first), 300));

    // Negative deltas, then positive ones, so a descending and an ascending
    // walk both cross the signed varint width boundaries.
    let mut descending: Vec<V> = Vec::new();
    let mut at = bounds.last().copied().unwrap_or(0);
    for _ in 0..64 {
        descending.push(V::S(at));
        at = (at - 1).max(lo);
    }
    push!("descending", descending);
    let mut ascending: Vec<V> = Vec::new();
    let mut at = first;
    for _ in 0..64 {
        ascending.push(V::S(at));
        at = (at + 1).min(hi);
    }
    push!("ascending", ascending);

    for i in 0..bounds.len().saturating_sub(1) {
        push!(
            format!("pair_{i}"),
            vec![V::S(bounds[i]), V::S(bounds[i + 1])]
        );
    }
    push!(
        "boundary_walk",
        bounds.iter().copied().map(V::S).collect::<Vec<V>>()
    );

    // A width change in the middle of a stream: a one-byte delta, then a
    // four-byte one, then a one-byte one again.
    push!(
        "width_jump",
        vec![V::S(0), V::S(1), V::S(1 << 20), V::S((1 << 20) + 1), V::S(2)]
    );
    push!(
        "width_jump_down",
        vec![V::S(1 << 30), V::S(1), V::S(2), V::S(1 << 20)]
    );

    if ty.nullable() {
        push!("null_alone", vec![V::N]);
        push!("null_then_value", vec![V::N, V::S(first)]);
        push!("value_then_null", vec![V::S(first), V::N]);
        // A null between two equal values: the delta after the null is
        // measured from the last *non-null*, not from the null.
        push!("null_between_equal", vec![V::S(first), V::N, V::S(first)]);
        push!(
            "nulls_between_differing",
            vec![
                V::S(first),
                V::N,
                V::S(first + 1),
                V::N,
                V::N,
                V::S(first),
            ]
        );
        push!(
            "null_sandwiched",
            [repeat(V::N, 70), vec![V::S(first)], repeat(V::N, 70)].concat()
        );
    }

    out.extend(random_cases_in(
        ty,
        lo.max(-(1i128 << 35)),
        hi.min(1i128 << 35),
    ));
    out
}

/// The prefix corpus for one type: row lengths, with the null placements a
/// nullable prefix column admits.
fn prefix_cases(ty: Ty) -> Vec<Case> {
    let bounds: Vec<i128> = PREFIX_BOUNDARY
        .iter()
        .copied()
        .filter(|v| ty.in_domain(*v))
        .collect();
    let first = bounds.first().copied().unwrap_or(0);
    let mut out: Vec<Case> = Vec::new();

    macro_rules! push {
        ($name:expr, $values:expr) => {
            out.push(Case {
                name: $name.to_string(),
                seed: 0,
                values: $values,
            })
        };
    }

    push!("empty", vec![]);
    push!("one", vec![V::S(first)]);
    push!("zero_length", vec![V::S(0)]);
    push!("zero_lengths_5", repeat(V::S(0), 5));
    push!("all_equal_64", repeat(V::S(3), 64));
    for &count in RUN_COUNTS {
        push!(format!("length_{count}"), repeat(V::S(3), count));
    }
    for i in 0..bounds.len().saturating_sub(1) {
        push!(
            format!("pair_{i}"),
            vec![V::S(bounds[i]), V::S(bounds[i + 1])]
        );
    }
    push!(
        "boundary_lengths",
        bounds.iter().copied().map(V::S).collect::<Vec<V>>()
    );
    // A row length that is a prefix of the run beside it, diverging at the
    // first row, at the last row, and at both ends.
    push!(
        "diverges_first",
        [repeat(V::S(7), 40), vec![V::S(9)], repeat(V::S(7), 40)].concat()
    );
    push!(
        "diverges_last",
        [repeat(V::S(7), 80), vec![V::S(9)]].concat()
    );
    push!(
        "diverges_both",
        [repeat(V::S(7), 40), vec![V::S(9)], repeat(V::S(7), 39), vec![V::S(9)]].concat()
    );
    // A row of no length in the middle: the sum does not move, so the
    // offsets either side of it are the same.
    push!(
        "zero_in_middle",
        vec![V::S(1), V::S(2), V::S(0), V::S(3), V::S(0), V::S(4)]
    );

    if ty.nullable() {
        push!("null_alone", vec![V::N]);
        push!("null_then_length", vec![V::N, V::S(first)]);
        push!("length_then_null", vec![V::S(first), V::N]);
        push!(
            "nulls_between",
            vec![V::S(1), V::N, V::S(2), V::N, V::N, V::S(3)]
        );
        push!(
            "null_runs",
            [vec![V::S(1)], repeat(V::N, 70), repeat(V::S(1), 70)].concat()
        );
    }

    out.extend(random_cases(ty));
    out
}

// ── Encoding through the reference ───────────────────────────────────────────

/// A present value, narrowed to the column type's own integer.
///
/// A `None` in a non-nullable case is a bug in the corpus rather than an
/// input, so it panics here where the case that built it is on the stack.
fn plain<T>(v: &V, f: impl Fn(i128) -> T) -> T {
    match v {
        V::S(x) => f(*x),
        V::N => panic!("a non-nullable case carried a null"),
    }
}

/// A value that may be absent, narrowed to the column type's own integer.
fn maybe<T>(v: &V, f: impl Fn(i128) -> T) -> Option<T> {
    match v {
        V::S(x) => Some(f(*x)),
        V::N => None,
    }
}

/// The reference's RLE bytes for `values`.
///
/// Every arm drives the reference's own RLE encoder for that column type —
/// `RleEncoder` over `u64`, `i64`, `u32`, `i32` and the nullable forms
/// (`lib.rs:566-601`, `:604-641`) — so these are the reference's bytes and
/// not a re-implementation of them.
///
/// **The arms are spelled out rather than generated.** The eight differ only
/// in the element type, and a macro over that type put the type in a
/// qualified-path position where it did not belong; eight short `match` arms
/// read better than the macro did.
fn rle_bytes(ty: Ty, values: &[V]) -> Vec<u8> {
    match ty {
        Ty::U64 => {
            let mut enc = RleEncoder::<u64>::new();
            for v in values {
                enc.append(plain(v, |x| x as u64));
            }
            enc.save()
        }
        Ty::I64 => {
            let mut enc = RleEncoder::<i64>::new();
            for v in values {
                enc.append(plain(v, |x| x as i64));
            }
            enc.save()
        }
        Ty::U32 => {
            let mut enc = RleEncoder::<u32>::new();
            for v in values {
                enc.append(plain(v, |x| x as u32));
            }
            enc.save()
        }
        Ty::I32 => {
            let mut enc = RleEncoder::<i32>::new();
            for v in values {
                enc.append(plain(v, |x| x as i32));
            }
            enc.save()
        }
        Ty::OptU64 => {
            let mut enc = RleEncoder::<Option<u64>>::new();
            for v in values {
                enc.append(maybe(v, |x| x as u64));
            }
            enc.save()
        }
        Ty::OptI64 => {
            let mut enc = RleEncoder::<Option<i64>>::new();
            for v in values {
                enc.append(maybe(v, |x| x as i64));
            }
            enc.save()
        }
        Ty::OptU32 => {
            let mut enc = RleEncoder::<Option<u32>>::new();
            for v in values {
                enc.append(maybe(v, |x| x as u32));
            }
            enc.save()
        }
        Ty::OptI32 => {
            let mut enc = RleEncoder::<Option<i32>>::new();
            for v in values {
                enc.append(maybe(v, |x| x as i32));
            }
            enc.save()
        }
        Ty::Bool => unreachable!("bool is not an RLE type"),
    }
}

/// The reference's boolean bytes for `values`, through the boolean encoder
/// (`bool.rs:1653-1667` for the shapes this corpus holds).
fn bool_bytes(values: &[V]) -> Vec<u8> {
    let mut enc = BoolEncoder::<Leb128>::new();
    for v in values {
        enc.append(plain(v, |x| x != 0));
    }
    enc.save()
}

/// The reference's delta bytes for `values`, through the delta encoder
/// (`delta/mod.rs:502-559`).
///
/// `u32` and `u64` go through the 64-bit delta types and `i32` and `i64`
/// through the 64-bit signed ones: every delta type's `Inner` is `i64`
/// (`delta/mod.rs:138-222`), so the wire is one signed varint either way and
/// the values are the same numbers.
fn delta_bytes(ty: Ty, values: &[V]) -> Vec<u8> {
    match ty {
        Ty::U64 | Ty::U32 => {
            let mut enc = DeltaEncoder::<u64>::new();
            for v in values {
                enc.append(plain(v, |x| x as u64));
            }
            enc.save()
        }
        Ty::I64 | Ty::I32 => {
            let mut enc = DeltaEncoder::<i64>::new();
            for v in values {
                enc.append(plain(v, |x| x as i64));
            }
            enc.save()
        }
        Ty::OptU64 | Ty::OptU32 => {
            let mut enc = DeltaEncoder::<Option<u64>>::new();
            for v in values {
                enc.append(maybe(v, |x| x as u64));
            }
            enc.save()
        }
        Ty::OptI64 | Ty::OptI32 => {
            let mut enc = DeltaEncoder::<Option<i64>>::new();
            for v in values {
                enc.append(maybe(v, |x| x as i64));
            }
            enc.save()
        }
        Ty::Bool => unreachable!("bool is not a delta type"),
    }
}

/// What the reference says about a slab's bytes: the item count and the run
/// count from `validate_encoding`, the tail metadata, and where its
/// *loader* would cut them.
struct SlabAnswer {
    len: usize,
    segments: usize,
    tail_bytes: u32,
    tail_lit_tail: Option<u32>,
    /// The item count of each slab the loader produced.
    split: Vec<usize>,
}

/// The reference's own metadata for an RLE-shaped slab, for one encoding.
///
/// Generic over the encoding rather than over the value type, because the
/// run walk, the tail and the load cut are the same for every RLE family and
/// only the element type — which decides whether a null run is legal —
/// differs. That is what the caller dispatches on.
fn rle_slab_of<E: ColumnEncoding>(
    bytes: &[u8],
) -> Result<SlabAnswer, Box<dyn Error>> {
    let info = E::validate_encoding(bytes)
        .map_err(|e| -> Box<dyn Error> { e.to_string().into() })?;
    let (tail_bytes, tail_lit_tail) = tail_fields(&format!("{:?}", info.tail));
    let mut it = E::load_iter(bytes, LOADER_MAX_SEGMENTS);
    loop {
        match it.try_next_run() {
            Ok(Some(_)) => {}
            Ok(None) => break,
            Err(e) => return Err(e.to_string().into()),
        }
    }
    let split = (0..it.slabs_completed())
        .map(|i| it.completed_slab_len(i))
        .collect();
    Ok(SlabAnswer {
        len: info.len,
        segments: info.segments,
        tail_bytes,
        tail_lit_tail,
        split,
    })
}

/// The reference's own metadata for an RLE-shaped slab.
fn rle_slab(ty: Ty, bytes: &[u8]) -> Result<SlabAnswer, Box<dyn Error>> {
    match ty {
        Ty::U64 => rle_slab_of::<RleEncoding<u64>>(bytes),
        Ty::I64 => rle_slab_of::<RleEncoding<i64>>(bytes),
        Ty::U32 => rle_slab_of::<RleEncoding<u32>>(bytes),
        Ty::I32 => rle_slab_of::<RleEncoding<i32>>(bytes),
        Ty::OptU64 => rle_slab_of::<RleEncoding<Option<u64>>>(bytes),
        Ty::OptI64 => rle_slab_of::<RleEncoding<Option<i64>>>(bytes),
        Ty::OptU32 => rle_slab_of::<RleEncoding<Option<u32>>>(bytes),
        Ty::OptI32 => rle_slab_of::<RleEncoding<Option<i32>>>(bytes),
        Ty::Bool => unreachable!("bool is not an RLE type"),
    }
}

/// The reference's own metadata for a boolean slab. The boolean tail *is*
/// the width of the last count, as a `u8` (`encoder.rs:674-676`).
fn bool_slab(bytes: &[u8]) -> Result<SlabAnswer, Box<dyn Error>> {
    let info = <BoolEncoding as ColumnEncoding>::validate_encoding(bytes)
        .map_err(|e| -> Box<dyn Error> { e.to_string().into() })?;
    let mut it = <BoolEncoding as ColumnEncoding>::load_iter(bytes, LOADER_MAX_SEGMENTS);
    loop {
        match it.try_next_run() {
            Ok(Some(_)) => {}
            Ok(None) => break,
            Err(e) => return Err(e.to_string().into()),
        }
    }
    let split = (0..it.slabs_completed())
        .map(|i| it.completed_slab_len(i))
        .collect();
    Ok(SlabAnswer {
        len: info.len,
        segments: info.segments,
        tail_bytes: u32::from(info.tail),
        tail_lit_tail: None,
        split,
    })
}

/// The two fields of a reference `RleTail`, read out of its `Debug` text.
///
/// **`RleTail`'s fields are `pub(crate)`** (`rle/mod.rs:98-102`), so `Debug`
/// is the only public way to read them, and the record wants them as numbers
/// rather than as text.
fn tail_fields(text: &str) -> (u32, Option<u32>) {
    let bytes = read_usize_after(text, "bytes: ").unwrap_or(0) as u32;
    let lit_tail = if text.contains("lit_tail: None") {
        None
    } else {
        read_usize_after(text, "lit_tail: Some(").map(|n| n as u32)
    };
    (bytes, lit_tail)
}

/// The decimal number after `marker`, or `None` when the marker is absent.
fn read_usize_after(text: &str, marker: &str) -> Option<usize> {
    let at = text.find(marker)? + marker.len();
    let digits: String = text[at..]
        .chars()
        .take_while(char::is_ascii_digit)
        .collect();
    digits.parse().ok()
}

/// The reference's `get_prefix(i)` for every `i` in `0..=len`.
fn prefix_sums(ty: Ty, values: &[V]) -> Vec<Json> {
    macro_rules! sums {
        ($col:ident, $t:ty, $wrap:expr) => {{
            let mut col: PrefixColumn<$t> = PrefixColumn::new();
            for v in values {
                col.push($wrap(v));
            }
            (0..=values.len())
                .map(|i| Json::String(col.get_prefix(i).to_string()))
                .collect()
        }};
    }
    match ty {
        Ty::U32 | Ty::I32 => sums!(col, u32, |v: &V| match v {
            V::S(x) => *x as u32,
            V::N => panic!("a non-nullable case carried a null"),
        }),
        Ty::U64 => sums!(col, u64, |v: &V| match v {
            V::S(x) => *x as u64,
            V::N => panic!("a non-nullable case carried a null"),
        }),
        Ty::I64 => sums!(col, i64, |v: &V| match v {
            V::S(x) => *x as i64,
            V::N => panic!("a non-nullable case carried a null"),
        }),
        Ty::OptU32 | Ty::OptI32 => sums!(col, Option<u32>, |v: &V| match v {
            V::S(x) => Some(*x as u32),
            V::N => None,
        }),
        Ty::OptU64 => sums!(col, Option<u64>, |v: &V| match v {
            V::S(x) => Some(*x as u64),
            V::N => None,
        }),
        Ty::OptI64 => sums!(col, Option<i64>, |v: &V| match v {
            V::S(x) => Some(*x as i64),
            V::N => None,
        }),
        Ty::Bool => vec![Json::String("0".into())],
    }
}

/// The reference's `get_index_for_prefix` for each target, where the
/// reference has the method at all.
///
/// `get_index_for_prefix` sits behind an `UnsignedPrefix` bound
/// (`prefix.rs:588-621`) and `i128` — what a signed prefix column
/// accumulates into (`prefix.rs:249-256`) — is not one, so a signed column
/// reports `null` rather than a value the reference cannot produce.
fn prefix_indexes(ty: Ty, values: &[V], targets: &[i128]) -> Option<Vec<Json>> {
    // The target is cast to the column's own accumulator width, which is
    // not the corpus's `i128`: `u32` rows sum into `u64` and `u64` rows into
    // `u128` (`prefix.rs:259-266`). A `let at: _` does not pick those up.
    macro_rules! indexes {
        ($t:ty, $prefix:ty, $wrap:expr) => {{
            let mut col: PrefixColumn<$t> = PrefixColumn::new();
            for v in values {
                col.push($wrap(v));
            }
            Some(
                targets
                    .iter()
                    .map(|t| {
                        Json::String(col.get_index_for_prefix(*t as $prefix).to_string())
                    })
                    .collect(),
            )
        }};
    }
    match ty {
        Ty::U32 | Ty::I32 => indexes!(u32, u64, |v: &V| match v {
            V::S(x) => *x as u32,
            V::N => panic!("a non-nullable case carried a null"),
        }),
        Ty::U64 => indexes!(u64, u128, |v: &V| match v {
            V::S(x) => *x as u64,
            V::N => panic!("a non-nullable case carried a null"),
        }),
        Ty::OptU32 | Ty::OptI32 => indexes!(Option<u32>, u64, |v: &V| match v {
            V::S(x) => Some(*x as u32),
            V::N => None,
        }),
        Ty::OptU64 => indexes!(Option<u64>, u128, |v: &V| match v {
            V::S(x) => Some(*x as u64),
            V::N => None,
        }),
        // A signed prefix column: no `UnsignedPrefix`, so no answer.
        Ty::I64 | Ty::OptI64 | Ty::Bool => None,
    }
}

/// The targets `get_index_for_prefix` is asked for. They are the reference's
/// own, so the Zig side walks the same list rather than a list of its own.
fn prefix_index_targets(ty: Ty, values: &[V]) -> Vec<i128> {
    let mut targets: Vec<i128> = vec![0, 1, 2, 3];
    if let Some(V::S(last)) = values.last() {
        targets.push(*last);
        targets.push(*last / 2);
    }
    for v in values.iter().take(8) {
        if let V::S(x) = v {
            targets.push(*x);
        }
    }
    let (lo, hi) = ty.domain();
    targets.retain(|t| *t >= lo && *t <= hi);
    targets.sort_unstable();
    targets.dedup();
    targets
}

// ── The btree corpus ─────────────────────────────────────────────────────────

/// One btree case: the values, and the ranges to ask about.
struct BtreeCase {
    name: String,
    seed: u64,
    values: Vec<i64>,
    queries: Vec<(i64, i64)>,
}

/// The btree corpus.
///
/// The four shapes are the four named: **ascending** (every delta positive,
/// so the prefix sum never decreases and the pruning is one-sided),
/// **descending**, **all equal** (every delta after the first is zero, so
/// `min_offset == max_offset` and the tree's range test is tightest), and
/// **random**. Plus **one more slab than a page holds**: 65 values, which at
/// one value per slab is 65 slabs against a branch factor of 64
/// (`btree.rs:194-197`), so the tree has to grow a second level.
fn btree_cases() -> Vec<BtreeCase> {
    let mut out: Vec<BtreeCase> = Vec::new();
    let mut push = |name: &str, seed: u64, values: Vec<i64>| {
        let queries = btree_queries(seed, &values);
        out.push(BtreeCase {
            name: name.to_string(),
            seed,
            values,
            queries,
        });
    };

    push("empty", 0, vec![]);
    push("one", 0, vec![0]);
    push("all_equal_100", 0, vec![7; 100]);
    push("all_zero_100", 0, vec![0; 100]);
    push("ascending_200", 0, (0..200).collect());
    push("descending_200", 0, (0..200).rev().collect());
    // One more slab than a page holds, at one value per slab, and the same
    // shape descending.
    push("page_plus_one", 0, (0..65).collect());
    push("page_plus_one_descending", 0, (0..65).rev().collect());
    push("page_plus_one_constant", 0, vec![-3; 65]);
    // Two pages, so the root splits and both children are internal.
    push("two_pages", 0, (0..129).collect());
    for k in 0..12u64 {
        let seed = case_seed(2000 + k);
        let mut rng = Lcg::new(seed);
        let n = 1 + rng.below(160) as usize;
        let mut values: Vec<i64> = Vec::with_capacity(n);
        let mut at = (rng.below(21) as i64) - 10;
        for _ in 0..n {
            values.push(at);
            at = (at + (rng.below(7) as i64) - 3).clamp(-1000, 1000);
        }
        push(&format!("random_{k}"), seed, values);
    }
    out
}

/// The ranges one case is asked about: the empty range, everything, six
/// ranges drawn around real values, and two past the end.
fn btree_queries(seed: u64, values: &[i64]) -> Vec<(i64, i64)> {
    // **A wide range, but not the widest.** `find_by_range` computes
    // `self.hi - a` for every run with no check (`delta/indexed.rs:291-293`),
    // so an upper bound of `i64::MAX` overflows against a negative realized
    // value and panics in a debug build. Half the `i64` range covers every
    // value this corpus generates, and the query bounds are the caller's
    // rather than the column's, so nothing clamps them here.
    let mut queries: Vec<(i64, i64)> = vec![(0, 0), (i64::MIN / 2, i64::MAX / 2)];
    if values.is_empty() {
        return queries;
    }
    let mut rng = Lcg::new(seed ^ 0xA5A5_5A5A_1234_5678);
    for _ in 0..6 {
        let pick = values[rng.below(values.len() as u64) as usize];
        let lo = pick.saturating_sub(1 + rng.below(3) as i64);
        let hi = lo.saturating_add(1 + rng.below(6) as i64);
        queries.push((lo, hi));
    }
    let last = *values.last().unwrap();
    queries.push((last, last + 1));
    queries.push((last + 1, last + 2));
    queries
}

/// The reference's answer to one range query: every index whose realized
/// value lies in `[lo, hi)`, in index order.
///
/// This is the delta column's B-tree doing the work — `find_by_range` walks
/// `find_by_value_range` over the index and then scans the candidate slabs
/// (`delta/indexed.rs:167-215`) — so it is the tree's own answer and not an
/// arithmetic identity the test could have written itself.
fn btree_answer(values: &[i64], lo: i64, hi: i64) -> Vec<usize> {
    let mut col = DeltaColumn::<i64>::new();
    for v in values {
        col.push(*v);
    }
    col.find_by_range(lo..hi).collect()
}

