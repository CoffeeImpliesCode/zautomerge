// ── The generator ────────────────────────────────────────────────────────────

/// The LCG's multiplier: `0x5851F42D4C957F2D`, which is 6364136223846793005.
const LCG_MUL: u64 = 0x5851_F42D_4C957_F2D;

/// The LCG's increment: `0x14057B7EF767814F`, which is 1442695040888963407.
const LCG_ADD: u64 = 0x1405_7B7E_F767_814F;

/// The seed every case's stream is derived from. A case's own seed is this
/// value mixed with its index, so one case is replayable on its own.
const BASE_SEED: u64 = 0x5EED_0C0D_EC0D_0001;

/// How many successive states the `codec-lcg` record publishes, so the Zig
/// side can prove its generator is this one before it trusts a corpus
/// generated by it.
const LCG_STATES: usize = 16;

/// The budget the reference's *loader* is given when this file asks where it
/// would cut. Sixty-four is the crate's own default (`column.rs:21`), and the
/// loader cuts at half of it (`rle/load.rs:193`).
const LOADER_MAX_SEGMENTS: usize = 64;

/// A 64-bit linear congruential generator, `state = state * MUL + ADD`, both
/// operations wrapping.
///
/// **A deliberate LCG and not `rand`.** A failure has to be replayable from
/// the seed in its record, and `rand`'s stream is a property of the crate
/// version rather than of this file. The Zig side carries the same three
/// constants, and the `codec-lcg` record pins them, so the two generators
/// cannot drift apart silently.
struct Lcg(u64);

impl Lcg {
    fn new(seed: u64) -> Self {
        Lcg(seed)
    }

    /// The next state, which is also the next output.
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_mul(LCG_MUL).wrapping_add(LCG_ADD);
        self.0
    }

    /// A value in `0..n`, or `0` when `n` is zero.
    fn below(&mut self, n: u64) -> u64 {
        if n == 0 {
            return 0;
        }
        self.next() % n
    }
}

