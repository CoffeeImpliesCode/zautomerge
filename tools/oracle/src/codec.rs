//! The codec differential corpus.
//!
//! Every other subcommand drives the reference through its *document* API.
//! This one drives it through its *column codecs* — the RLE encoder, the
//! boolean encoder, the delta encoder, the prefix column and the
//! load-time slab cutter — and prints, for a corpus of values, the bytes
//! the reference itself produced.
//!
//! Each record carries the reference's bytes for a named input.
//! The Zig tests compare their encoded bytes with this corpus.
//!
//! # The corpus
//!
//! Two kinds of case, and the second is the point:
//!
//! * **Hand-built boundary cases.** A single run; two runs; every run count
//!   whose LEB128 width changes (2, 3, 4, 63, 64, 65, 127, 128, 129, 130,
//!   16 383, 16 384, 16 385); every value whose width changes, signed and
//!   unsigned, positive and negative; the empty slab; a run of nulls; a null
//!   at each end. These are the inputs a codec is *most* likely to get
//!   right, which is exactly why they cannot be the only ones.
//! * **Seeded-LCG random streams**, twenty-four per column type, in four
//!   shapes: a small alphabet (so runs form and merge), the full domain (so
//!   widths vary inside one slab), explicit blocks of equal values, and a
//!   random walk. The generator is [`Lcg`], a 64-bit LCG with its
//!   multiplier and increment spelled out below — no `rand`, no wall clock,
//!   no thread state, so a failing case is reproducible from the seed in
//!   its record.
//!
//! # Why the values are printed in runs
//!
//! A record holds `"runs": [[count, value], …]`, not the expanded list. A
//! 16 385-value repeat run is 16 385 numbers in a JSON file and about
//! twenty bytes in this form, and the run form is lossless: the Zig side
//! expands it and the expansion is the input both sides encoded.
//!
//! # What a record carries
//!
//! | field      | what it is |
//! |------------|------------|
//! | `codec`    | the column type, e.g. `rle-i64` |
//! | `case`     | the case's name; its `seed` is beside it |
//! | `runs`     | the input, as maximal runs |
//! | `len`      | how many values the runs hold |
//! | `hex`      | **the reference's bytes for that input** |
//! | `slab_len`, `segments` | the reference's own metadata for those bytes, from `validate_encoding` |
//! | `tail_bytes`, `tail_lit_tail` | the reference's tail metadata for those bytes |
//! | `split`    | where the reference's *loader* cuts them, at its own budget |
//! | `prefixes`, `index_targets`, `indexes` | prefix columns: the reference's `get_prefix` for every `i`, and `get_index_for_prefix` for the listed targets |
//! | `queries`  | btree cases: the reference's `find_by_range` answers |

