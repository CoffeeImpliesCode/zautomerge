impl Ty {
    /// The record's `codec` field, and the name the Zig side switches on.
    fn name(self) -> &'static str {
        match self {
            Ty::U64 => "rle-u64",
            Ty::I64 => "rle-i64",
            Ty::U32 => "rle-u32",
            Ty::I32 => "rle-i32",
            Ty::OptU64 => "rle-opt-u64",
            Ty::OptI64 => "rle-opt-i64",
            Ty::OptU32 => "rle-opt-u32",
            Ty::OptI32 => "rle-opt-i32",
            Ty::Bool => "bool",
        }
    }

    /// The record's `codec` field with the `rle-` family prefix taken off,
    /// for the delta and prefix families, whose names are the same suffix.
    fn bare(self) -> &'static str {
        self.name().trim_start_matches("rle-")
    }

    fn nullable(self) -> bool {
        matches!(
            self,
            Ty::OptU64 | Ty::OptI64 | Ty::OptU32 | Ty::OptI32
        )
    }

    /// The value domain, as `(lo, hi)`. `u64` stops at `i64::MAX` only for
    /// a *delta* column, whose realized values are the domain
    /// (`delta/mod.rs:157-186`); an RLE column of `u64` holds all of it.
    fn domain(self) -> (i128, i128) {
        match self {
            Ty::U64 | Ty::OptU64 => (0, u64::MAX as i128),
            Ty::I64 | Ty::OptI64 => (i64::MIN as i128, i64::MAX as i128),
            Ty::U32 | Ty::OptU32 => (0, u32::MAX as i128),
            Ty::I32 | Ty::OptI32 => (i32::MIN as i128, i32::MAX as i128),
            Ty::Bool => (0, 1),
        }
    }

    /// The value domain of the same type as a *delta* column holds, which
    /// is `u64` and `u32` clamped to `i64::MAX` and `None` for `bool`.
    fn delta_domain(self) -> Option<(i128, i128)> {
        match self {
            Ty::U64 | Ty::OptU64 => Some((0, i64::MAX as i128)),
            Ty::U32 | Ty::OptU32 => Some((0, u32::MAX as i128)),
            Ty::I64 | Ty::OptI64 => Some((i64::MIN as i128, i64::MAX as i128)),
            Ty::I32 | Ty::OptI32 => Some((i32::MIN as i128, i32::MAX as i128)),
            Ty::Bool => None,
        }
    }

    fn in_domain(self, v: i128) -> bool {
        let (lo, hi) = self.domain();
        v >= lo && v <= hi
    }
}

/// One corpus value: a present one, in the type's domain, or an absent one.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum V {
    S(i128),
    N,
}

impl V {
    fn json(self) -> Json {
        match self {
            V::S(x) => Json::String(x.to_string()),
            V::N => Json::Null,
        }
    }
}

